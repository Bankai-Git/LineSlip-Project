CREATE TABLE slips (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_user_id TEXT NOT NULL CHECK (length(btrim(line_user_id)) > 0),
  message_id TEXT NOT NULL CHECK (length(btrim(message_id)) > 0),
  webhook_event_id TEXT,
  reference_no TEXT NOT NULL CHECK (length(btrim(reference_no)) > 0),
  amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
  transaction_date DATE NOT NULL,
  transaction_time TIME,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed')),
  ocr_confidence NUMERIC(5, 2) CHECK (ocr_confidence BETWEEN 0 AND 100),
  received_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  confirmed_at TIMESTAMPTZ,
  CONSTRAINT slips_confirmation_timestamp_check CHECK (
    (status = 'pending' AND confirmed_at IS NULL)
    OR (status = 'confirmed' AND confirmed_at IS NOT NULL)
  )
);

CREATE UNIQUE INDEX slips_user_reference_unique
  ON slips (line_user_id, reference_no);

CREATE UNIQUE INDEX slips_user_message_unique
  ON slips (line_user_id, message_id);

CREATE UNIQUE INDEX slips_webhook_event_unique
  ON slips (webhook_event_id)
  WHERE webhook_event_id IS NOT NULL;

CREATE INDEX slips_user_status_created_idx
  ON slips (line_user_id, status, created_at DESC);
